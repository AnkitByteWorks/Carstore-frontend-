export function getCarTelemetry(idOrName: number | string): CarTelemetry | null {
  if (typeof idOrName === "number") {
    const found = CAR_TELEMETRY_DATA.find((c) => c.id === idOrName);
    if (found) return found;
  }

  const query = String(idOrName).toLowerCase().trim();
  return (
    CAR_TELEMETRY_DATA.find(
      (c) =>
        c.name.toLowerCase().includes(query) ||
        query.includes(c.name.toLowerCase()) ||
        `${c.brand} ${c.name}`.toLowerCase().includes(query)
    ) || null
  );
}
